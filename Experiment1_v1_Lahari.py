"""Step3. Construct the impulse response

We model the room as
$$h[n] = \delta[n] + \sum_{i=1}^{M} a_i \delta[n-d_i]$$

The first term represents the direct sound. Each remaining term represents a delayed reflection. The delays and amplitudes below are chosen values for this simulation
"""

import os
os.makedirs("outputs", exist_ok=True)

delays_ms = [30, 60, 100]
amps = [0.60, 0.35, 0.20]

delays = [round(t * fs / 1000) for t in delays_ms]

h = np.zeros(max(delays) + 1)
h[0] = 1.0
for d, a in zip(delays, amps):
    h[d] += a

print("Sampling frequency:", fs, "Hz")
print("Delays in samples:", delays)
print("Impulse response length:", len(h), "samples")

nonzero = np.nonzero(h)[0]
plt.figure(figsize=(10, 4))
plt.stem(nonzero / fs * 1000, h[nonzero])
plt.title("Room Impulse Response")
plt.xlabel("Time (ms)")
plt.ylabel("Amplitude")
plt.grid(True)
plt.tight_layout()
plt.savefig("outputs/impulse_response.png", dpi=150)
plt.show()

"""Step4:Apply reverberation using manual convolution

The convolution for this impulse response can be written as a sum of delayed versions of the input signal. Because only non-zero samples of h are used, only these samples will be iterated through in the loop below.
"""

def manual_convolution(x, h):
    """Convolve x with h by adding shifted, scaled copies of x."""
    y = np.zeros(len(x) + len(h) - 1)
    for k in np.nonzero(h)[0]:
        y[k:k + len(x)] += h[k] * x
    return y

y = manual_convolution(x, h)

print("Input samples:", len(x))
print("Output samples:", len(y))
print(f"Input duration: {len(x) / fs:.3f} s")
print(f"Output duration: {len(y) / fs:.3f} s")

peak = np.max(np.abs(y))
y_audio = 0.9 * y / peak if peak > 0 else y.copy()
os.makedirs("outputs", exist_ok=True)
sf.write("outputs/reverberated_guitar.wav", y_audio, fs)

print("Original guitar")
display(Audio(x, rate=fs))
print("Reverberated guitar")
display(Audio(y_audio, rate=fs))

"""Step5: Compare the waveforms

The reverberated signal extends beyond the original because the last delayed copy continues after the input ends. Overlapping copies can also make some peaks larger.
"""

plt.figure(figsize=(12, 4))
plt.plot(np.arange(len(x)) / fs, x, label="Original", linewidth=0.6)
