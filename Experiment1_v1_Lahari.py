"""Step6: Change the reflection parameters"""

def make_impulse_response(delays_ms, amplitudes, fs):
    delay_samples = [round(t * fs / 1000) for t in delays_ms]
    h_case = np.zeros(max(delay_samples) + 1)
    h_case[0] = 1.0
    for d, a in zip(delay_samples, amplitudes):
        h_case[d] += a
    return h_case

cases = {
    "Baseline": ([30, 60, 100], [0.60, 0.35, 0.20]),
    "Fewer reflections": ([30, 60], [0.60, 0.35]),
    "Longer delays": ([60, 120, 200], [0.60, 0.35, 0.20]),
    "Weaker reflections": ([30, 60, 100], [0.20, 0.10, 0.05]),
}


os.makedirs("outputs", exist_ok=True)
reverb_results = {}

for name, (case_delays, case_amps) in cases.items():
    h_case = make_impulse_response(case_delays, case_amps, fs)
    y_case = manual_convolution(x, h_case)

    reverb_results[name] = y_case

    filename = name.lower().replace(" ", "_") + ".wav"
    sf.write(f"outputs/{filename}", y_case, fs)

    print(f"{name}: {len(case_delays)} reflections")
    print(f"Output duration: {len(y_case) / fs:.3f} s")
    display(Audio(y_case, rate=fs))

"""### Observations

- **Baseline:** The original signal is combined with three delayed reflections of decreasing amplitudes, producing a reverberation effect.
- **Fewer reflections:** Reducing the number of reflections reduces the number of delayed copies added to the original signal.
- **Longer delays:** Increasing the reflection delays makes the reflected sounds arrive later, making them more separated from the direct sound.
- **Weaker reflections:** Reducing the reflection amplitudes makes the delayed copies quieter, resulting in a less pronounced reverberation effect.

Step7: Calculate the spectrum
"""

def manual_fft(signal):
    signal = np.asarray(signal, dtype=complex)
    n = len(signal)

    if n == 1:
        return signal

    if n & (n - 1) != 0:
        raise ValueError("Input length must be a power of two.")

    even = manual_fft(signal[::2])
    odd = manual_fft(signal[1::2])

    factor = np.exp(-2j * np.pi * np.arange(n // 2) / n) * odd

    return np.concatenate((even + factor, even - factor))


def spectrum_db(signal, nfft):
    padded = np.zeros(nfft)
    padded[:len(signal)] = signal

    S = np.abs(manual_fft(padded)[:nfft // 2])
    return 20 * np.log10(S / (S.max() + 1e-12) + 1e-12)

nfft = 2 ** int(np.ceil(np.log2(max(len(x), len(y_audio)))))
freq = np.arange(nfft // 2) * fs / nfft

X_db = spectrum_db(x, nfft)
Y_db = spectrum_db(y_audio, nfft)

print("FFT length:", nfft)

"""Step8: Compare the magnitude spectra"""

plt.figure(figsize=(11, 4.5))
